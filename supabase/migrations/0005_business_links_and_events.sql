-- ============================================================================
-- 업장 링크·혜택·로고 + 행사 날짜 미정 처리
--
--  1. 업장 바로가기 링크를 종류별로 나눈다.
--     값이 없는 링크는 화면에 아예 나오지 않는다.
--  2. 원청협 회원에게 주는 혜택을 업장마다 적어둔다.
--  3. 행사는 "5월 중" 처럼 날짜가 미정인 경우가 많다.
--     임원진 회의로 확정되면 관리자가 날짜·시간·장소를 채운다.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 업장 — 링크 / 로고 / 회원 혜택
-- ---------------------------------------------------------------------------
alter table businesses
  -- sns_url 하나로 뭉뚱그리던 것을 채널별로 나눈다
  add column if not exists blog_url      text,
  add column if not exists instagram_url text,
  -- 업장 로고 (사진과 별개)
  add column if not exists logo_image    text,
  -- 원청협 회원에게 제공하는 혜택. 비어 있으면 화면에 나오지 않는다.
  add column if not exists benefit       text;

-- ---------------------------------------------------------------------------
-- 행사 — 날짜 미정
--
-- date 는 정렬을 위해 반드시 있어야 하므로, 미정일 때는 해당 월 1일을 넣고
-- date_tbd 를 켠다. 화면에서는 "5월 중 (일정 미정)" 으로 보여준다.
-- ---------------------------------------------------------------------------
alter table posts
  add column if not exists date_tbd boolean not null default false;

comment on column posts.date_tbd is
  '날짜 미정 여부. 켜져 있으면 date 는 해당 월 1일이며 화면에는 "○월 중"으로 표시한다.';
