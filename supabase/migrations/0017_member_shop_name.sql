-- 0017. 가입 신청에 업장명
--
-- 홈페이지에서 직접 가입 신청을 받기로 했다. 받는 것은 세 가지뿐이다.
--   이름 · 업장명 · 연락처
--
-- 많이 물어보면 안 쓴다. 사업자등록번호나 주소 같은 것은 인사국이 승인하며
-- 따로 받는다. 홈페이지는 "누가 신청했는지" 만 알면 된다.
--
-- 이름과 연락처 칸은 이미 있고, 업장명 칸이 없어서 더한다.
-- businesses 표에 넣지 않는 이유는, 아직 승인 전이라 회원업장이 아니기 때문이다.
-- 승인이 끝난 뒤에 업장을 따로 등록한다.
-- ---------------------------------------------------------------------------

alter table members add column if not exists shop_name text;
